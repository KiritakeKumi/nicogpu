#!/usr/bin/env bash
# generate the "abstract prim" wrappers Ibex expects (prim_buf, prim_flop,
# prim_ram_1p, prim_clock_gating) without fusesoc/primgen.
#   gen_prim_shim.sh <ibex_root> <out_dir>
# The upstream flow runs lowRISC's primgen through a forked fusesoc; here each
# wrapper is the prim_generic implementation renamed (prim_generic_X -> prim_X).
# prim_clock_gating is replaced by a pass-through (no latch/BUFGCE clock gate in
# the FPGA CP; Ibex stays functionally identical, only the sleep power saving is lost).
set -eu
IBEX=${1:?ibex root}
OUT=${2:?out dir}
GEN=$IBEX/vendor/lowrisc_ip/ip/prim_generic/rtl
mkdir -p "$OUT"
for p in buf flop ram_1p; do
  sed "s/prim_generic_$p\b/prim_$p/g" "$GEN/prim_generic_$p.sv" > "$OUT/prim_$p.sv"
done
cat > "$OUT/prim_clock_gating.sv" <<'EOF'
// Pass-through replacement of prim_clock_gating (generated by gen_prim_shim.sh).
module prim_clock_gating #(
  parameter bit NoFpgaGate = 1'b0,
  parameter bit FpgaBufGlobal = 1'b1
) (
  input  logic clk_i,
  input  logic en_i,
  input  logic test_en_i,
  output logic clk_o
);
  logic unused_en;
  assign unused_en = en_i ^ test_en_i;
  assign clk_o = clk_i;
endmodule
EOF
