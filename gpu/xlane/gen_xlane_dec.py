#!/usr/bin/env python3
"""Generate ng_xlane_pkg.sv and ng_xlane_dec.sv

Same approach as rtl/gpu/valu/gen_valu_dec.py: match/mask and operand fields
come straight from the ISA YAML (rule: opcode + fixed fields + every unused
field must be zero, i.e. the model decoder's rule); only the name -> micro-op
mapping below is hand written.  Usage (repo root):

    python3 rtl/gpu/xlane/gen_xlane_dec.py [--out DIR] [--check-index vectors_xlane.isa_index.json]

The generated files are committed; CI only needs PyYAML for the staleness check.
"""
import argparse
import json
import os
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))

UOPS = """IDX UP DOWN XOR ROT QUAD WLANE DDXF DDYF DDXC DDYC SCAN BALLOT VANY VALL VEQ
RFIRST RADD RMINI RMAXI RMINU RMAXU RAND ROR RXOR RLANE""".split

UOP_OF = {
    "shfl.idx": "IDX", "shfl.bcast": "IDX", "shfl.up": "UP", "shfl.down": "DOWN",
    "shfl.xor": "XOR", "shfl.rot": "ROT", "quad.swizzle": "QUAD", "writelane": "WLANE",
    "fddx.fine.f32": "DDXF", "fddy.fine.f32": "DDYF", "fddx.coarse.f32": "DDXC",
    "fddy.coarse.f32": "DDYC", "xscan.add.u32": "SCAN", "ballot": "BALLOT",
    "vote.any": "VANY", "vote.all": "VALL", "vote.eq": "VEQ", "readfirst": "RFIRST",
    "xred.add.u32": "RADD", "xred.min.i32": "RMINI", "xred.max.i32": "RMAXI",
    "xred.min.u32": "RMINU", "xred.max.u32": "RMAXU", "xred.and.b32": "RAND",
    "xred.or.b32": "ROR", "xred.xor.b32": "RXOR", "readlane": "RLANE", "readlane.u": "RLANE",
}
FP_OPS = {"DDXF", "DDYF", "DDXC", "DDYC"}


def uop_of(name):
    for suf in (".vi", ".vu"):
        if name.endswith(suf):
            name = name[: -len(suf)]
    return UOP_OF[name]


def mask_of(fields):
    m = 0
    for hi, lo in fields:
        m |= ((1 << (hi - lo + 1)) - 1) << lo
    return m


def fx7(fld, name):
    hi, lo = fld[name]
    wd = hi - lo + 1
    if wd == 7:
        return "w[%d:%d]" % (hi, lo)
    return "{%d'd0, w[%d:%d]}" % (7 - wd, hi, lo)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--isa", default=os.path.join(ROOT, "spec", "isa", "nicogpu_isa.yaml"))
    ap.add_argument("--out", default=HERE)
    ap.add_argument("--check-index", help="isa_index.json from vecexport: compare match/mask")
    a = ap.parse_args()
    y = yaml.safe_load(open(a.isa, encoding="utf-8"))
    fmts = y["formats"]

    entries = []
    for ins in y["instructions"]:
        if ins["unit"] != "xlane":
            continue
        uop = uop_of(ins["name"])
        fm = fmts[ins["format"]]
        fld = fm["fields"]
        opf = {o["field"]: o for o in ins["operands"]}
        mask = mask_of([fld[k] for k in fld if k not in opf])
        match = 0
        for k, v in ins["fixed"].items():
            match |= v << fld[k][1]
        entries.append((ins, uop, fld, fm["width"], opf, mask, match))
    if len(entries) != 37:
        sys.exit("expected 37 xlane instructions, found %d" % len(entries))

    if a.check_index:
        idx = {i["name"]: i for i in json.load(open(a.check_index))["insns"]}
        bad = 0
        for ins, _u, _f, _w, _o, mask, match in entries:
            e = idx.get(ins["name"])
            if e is None or int(e["mask"], 16) != mask or int(e["match"], 16) != match:
                print("index mismatch:", ins["name"], hex(mask), hex(match), e)
                bad += 1
        have = {q[0]["name"] for q in entries}
        miss = [n for n, e in idx.items() if e["unit"] == "xlane" and n not in have]
        print("index check: %d entries, %d mismatches, xlane names in index without entry: %d" % (len(entries), bad, len(miss)))
        if bad or miss:
            sys.exit(1)

    with open(os.path.join(a.out, "ng_xlane_pkg.sv"), "w", newline="\n") as f:
        f.write("// GENERATED by gen_xlane_dec.py from -- do not edit.\n")
        f.write("// ng_xlane_pkg: micro-ops and decoded-instruction record of the cross-lane unit .\n")
        f.write("package ng_xlane_pkg;\n\n  // micro-op codes\n")
        for i, u in enumerate(UOPS):
            f.write("  localparam logic [4:0] U_%s = 5'd%d;\n" % (u, i))
        f.write(
            """
  // B operand (rs2 / immediate) classes
  localparam logic [1:0] B_NONE = 2'd0;
  localparam logic [1:0] B_VREG = 2'd1;  // per-lane vector register
  localparam logic [1:0] B_IMM  = 2'd2;  // instruction immediate (uimm8 / imm[4:0])
  localparam logic [1:0] B_UREG = 2'd3;  // uniform register, broadcast
  // destination kinds
  localparam logic [1:0] D_VREG = 2'd0;
  localparam logic [1:0] D_UREG = 2'd1;  // uniform result (ballot, vote, xred, readlane ...)
  localparam logic [1:0] D_WL   = 2'd2;  // writelane: one lane of a vector register, EXEC ignored

  // trap causes (model csr.h TrapCause)
  localparam logic [3:0] CAUSE_ILLEGAL  = 4'd1;
  localparam logic [3:0] CAUSE_FPEXC    = 4'd4;
  localparam logic [3:0] CAUSE_REGRANGE = 4'd10;

  typedef struct packed {
    logic        hit;      // recognised xlane encoding
    logic [4:0]  uop;
    logic        a_vec;    // rs1 is a vector source (all but writelane)
    logic [1:0]  b_kind;
    logic [1:0]  d_kind;
    logic        fp;       // derivative: MODE-driven f32 subtract
    logic        b_first;  // model reads rs2 before rs1 (range-trap order)
    logic [6:0]  rd;
    logic [6:0]  rs1;      // vector source; lane7 for writelane
    logic [6:0]  rs2;      // vector or uniform register
    logic [7:0]  imm;
  } dec_t;

endpackage
"""
        )

    lines = []
    by_op = {}
    for e in entries:
        by_op.setdefault(e[6] & 0x7F, []).append(e)
    for opc in sorted(by_op):
        lines.append("      7'd%d: begin" % opc)
        for ins, uop, fld, width, opf, mask, match in by_op[opc]:
            wmask = (1 << width) - 1
            cond = "(w & 32'h%08x) == 32'h%08x" % (mask & wmask, match & wmask)
            s = ["        // %s" % ins["name"], "        if (%s) begin" % cond]
            s.append("          d.hit = 1'b1; d.uop = U_%s;" % uop)
            name = ins["name"]
            a_vec = "1'b1"
            b_kind, d_kind = "B_NONE", "D_VREG"
            for fname, o in opf.items():
                kind = o["kind"]
                if fname == "rd":
                    d_kind = "D_UREG" if kind == "ureg" else "D_VREG"
                    s.append("          d.rd = %s;" % fx7(fld, "rd"))
                elif fname == "rs1":
                    if kind == "lane7":
                        a_vec = "1'b0"
                    s.append("          d.rs1 = %s;" % fx7(fld, "rs1"))
                elif fname == "rs2":
                    b_kind = "B_VREG" if kind == "vreg" else "B_UREG"
                    s.append("          d.rs2 = %s;" % fx7(fld, "rs2"))
                elif fname == "imm":
                    hi, lo = fld["imm"]
                    b_kind = "B_IMM"
                    if name == "quad.swizzle":
                        s.append("          d.imm = w[%d:%d];" % (hi, lo))
                    else:  # model: imm5 / "& 31" -- only bits [4:0] matter
                        s.append("          d.imm = {3'd0, w[%d:%d]};" % (lo + 4, lo))
                else:
                    raise ValueError((name, fname))
            if uop == "WLANE":
                d_kind = "D_WL"
            fl = []
            if uop in FP_OPS:
                fl.append("d.fp = 1'b1;")
            if uop in ("IDX", "XOR", "ROT") and b_kind == "B_VREG":
                fl.append("d.b_first = 1'b1;")
            s.append("          d.a_vec = %s; d.b_kind = %s; d.d_kind = %s;" % (a_vec, b_kind, d_kind))
            if fl:
                s.append("          " + " ".join(fl))
            s.append("        end")
            lines.extend(s)
        lines.append("      end")

    with open(os.path.join(a.out, "ng_xlane_dec.sv"), "w", newline="\n") as f:
        f.write("// GENERATED by gen_xlane_dec.py from -- do not edit.\n")
        f.write("// ng_xlane_dec: combinational decoder of the %d cross-lane instructions .\n" % len(entries))
        f.write("// Match/mask = opcode + fixed fields + every unused field must be zero, i.e. the\n")
        f.write("// model decoder's rule (checked against vecexport's isa_index by --check-index).\n")
        f.write("module ng_xlane_dec\n  import ng_xlane_pkg::*;\n(\n")
        f.write("  input  logic [31:0] w0,\n  output dec_t        d\n);\n")
        f.write("  logic [31:0] w;\n  assign w = w0;\n")
        f.write("  always_comb begin\n    d = '0;\n    case (w[6:0])\n")
        f.write("\n".join(lines))
        f.write("\n      default: ;\n    endcase\n  end\nendmodule\n")
    print("generated %d entries" % len(entries))


if __name__ == "__main__":
    main()
