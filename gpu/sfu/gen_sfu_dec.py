#!/usr/bin/env python3
"""Generate ng_sfu_pkg.sv and ng_sfu_dec.sv

The decode table (match/mask, operand fields) comes straight from the ISA
YAML so it cannot drift from the functional model's decoder; only the
name -> (lane op, format, MODE use) mapping below is hand written.  Usage
(repo root):

    python3 rtl/gpu/sfu/gen_sfu_dec.py [--check-index vectors_fp64_sfu.isa_index.json]

The generated files are committed; CI re-generates them and diffs.
"""
import argparse
import json
import os
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))

# lane op codes (ng_sfu_lane SOP_*)
SOP = {"RCP": 0, "SQRT": 1, "FDIV": 2, "RSQ": 3, "EXP2": 4, "LOG2": 5, "SIN": 6, "COS": 7, "IDIV": 8}
FMT = {"f16": 0, "f32": 1, "f64": 2}
IOP = {"div": 0, "divu": 1, "rem": 2, "remu": 3}
KIND = {"vreg": 1, "vpair": 2, "vreg16": 3}
BASE = {"rcp": "RCP", "rsq": "RSQ", "sqrt": "SQRT", "fsqrt": "SQRT", "exp2": "EXP2", "log2": "LOG2",
        "sin": "SIN", "cos": "COS", "fdiv": "FDIV"}


def sfu_op(name):
    """name -> (op, fmt, iop); KeyError if not an SFU instruction we know."""
    if name in IOP:
        return "IDIV", 1, IOP[name]
    base, _, ty = name.rpartition(".")
    return BASE[base], FMT[ty], 0


def mask_of(fields):
    m = 0
    for hi, lo in fields:
        m |= ((1 << (hi - lo + 1)) - 1) << lo
    return m


def fx8(fld, name):
    hi, lo = fld[name]
    wd = hi - lo + 1
    if wd == 8:
        return "w[%d:%d]" % (hi, lo)
    return "{%d'd0, w[%d:%d]}" % (8 - wd, hi, lo)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--isa", default=os.path.join(ROOT, "spec", "isa", "nicogpu_isa.yaml"))
    ap.add_argument("--out", default=HERE)
    ap.add_argument("--check-index", help="isa_index.json from vecexport: compare match/mask")
    a = ap.parse_args()
    y = yaml.safe_load(open(a.isa, encoding="utf-8"))
    fmts = y["formats"]

    entries = []
    for ins in y["instructions"]:
        if ins["unit"] != "sfu":
            continue
        op, fmt, iop = sfu_op(ins["name"])
        fm = fmts[ins["format"]]
        fld = fm["fields"]
        opf = {o["field"]: o for o in ins["operands"]}
        mask = mask_of([fld[k] for k in fld if k not in opf])
        match = 0
        for k, v in ins["fixed"].items():
            match |= v << fld[k][1]
        use_mode = "fp_mode" in ins.get("flags", [])
        entries.append((ins, op, fmt, iop, use_mode, fld, fm["width"], opf, mask, match))

    if a.check_index:
        idx = {i["name"]: i for i in json.load(open(a.check_index))["insns"]}
        bad = 0
        for ins, _o, _f, _i, _m, _fl, _w, _of, mask, match in entries:
            e = idx.get(ins["name"])
            if e is None or int(e["mask"], 16) != mask or int(e["match"], 16) != match:
                print("index mismatch:", ins["name"], hex(mask), hex(match), e)
                bad += 1
        have = {q[0]["name"] for q in entries}
        miss = [n for n, e in idx.items() if e["unit"] == "sfu" and n not in have]
        print("index check: %d entries, %d mismatches, sfu names in index without entry: %d" % (len(entries), bad, len(miss)))
        if bad or miss:
            sys.exit(1)

    with open(os.path.join(a.out, "ng_sfu_pkg.sv"), "w", newline="\n") as f:
        f.write("// GENERATED by gen_sfu_dec.py from -- do not edit.\n")
        f.write("// ng_sfu_pkg: lane op codes and decoded-instruction record of the SFU .\n")
        f.write("package ng_sfu_pkg;\n\n  // lane operation (ng_sfu_lane op input)\n")
        for k, v in SOP.items():
            f.write("  localparam logic [3:0] SOP_%s = 4'd%d;\n" % (k, v))
        f.write(
            """
  // operand kinds
  localparam logic [1:0] K_NONE   = 2'd0;
  localparam logic [1:0] K_VREG   = 2'd1;   // one 32-bit vector register
  localparam logic [1:0] K_VPAIR  = 2'd2;   // even-aligned register pair (binary64)
  localparam logic [1:0] K_VREG16 = 2'd3;   // half register: code = {reg, half}

  // trap causes (model csr.h TrapCause)
  localparam logic [3:0] CAUSE_ILLEGAL  = 4'd1;
  localparam logic [3:0] CAUSE_FPEXC    = 4'd4;
  localparam logic [3:0] CAUSE_REGRANGE = 4'd10;

  typedef struct packed {
    logic        hit;       // recognised SFU encoding
    logic [3:0]  op;        // SOP_*
    logic [1:0]  iop;       // integer divide flavour (0 div, 1 divu, 2 rem, 3 remu)
    logic [1:0]  fmt;       // 0 binary16, 1 binary32, 2 binary64 (operand/result format)
    logic        use_mode;  // instruction is subject to MODE (rm / DAZ / FTZ of `fmt`)
    logic [1:0]  a_kind;
    logic [1:0]  b_kind;
    logic [1:0]  d_kind;
    logic [7:0]  rd;        // register index, or {reg, half} for K_VREG16
    logic [7:0]  rs1;
    logic [7:0]  rs2;
  } dec_t;

endpackage
"""
        )

    by_op = {}
    for e in entries:
        by_op.setdefault(e[9] & 0x7F, []).append(e)
    lines = []
    for opc in sorted(by_op):
        lines.append("      7'd%d: begin" % opc)
        for ins, op, fmt, iop, use_mode, fld, width, opf, mask, match in by_op[opc]:
            wmask = (1 << width) - 1
            cond = "(w & 64'h%016x) == 64'h%016x" % (mask & wmask, match & wmask)
            s = ["        // %s" % ins["name"], "        if (%s) begin" % cond]
            s.append("          d.hit = 1'b1; d.op = SOP_%s; d.iop = 2'd%d; d.fmt = 2'd%d; d.use_mode = 1'b%d;" % (op, iop, fmt, int(use_mode)))
            kinds = {"rd": "K_NONE", "rs1": "K_NONE", "rs2": "K_NONE"}
            for fname, o in opf.items():
                if fname not in kinds:
                    raise ValueError((ins["name"], fname))
                kinds[fname] = {1: "K_VREG", 2: "K_VPAIR", 3: "K_VREG16"}[KIND[o["kind"]]]
                s.append("          d.%s = %s;" % (fname, fx8(fld, fname)))
            s.append("          d.d_kind = %s; d.a_kind = %s; d.b_kind = %s;" % (kinds["rd"], kinds["rs1"], kinds["rs2"]))
            s.append("        end")
            lines.extend(s)
        lines.append("      end")

    with open(os.path.join(a.out, "ng_sfu_dec.sv"), "w", newline="\n") as f:
        f.write("// GENERATED by gen_sfu_dec.py from -- do not edit.\n")
        f.write("// ng_sfu_dec: combinational decoder of the %d SFU instructions .\n" % len(entries))
        f.write("// Match/mask = opcode + fixed fields + every unused field must be zero, i.e. the\n")
        f.write("// model decoder's rule (checked against vecexport's isa_index by --check-index).\n")
        f.write("module ng_sfu_dec\n  import ng_sfu_pkg::*;\n(\n")
        f.write("  input  logic [31:0] w0,\n  input  logic [31:0] w1,\n  output dec_t        d\n);\n")
        f.write("  logic [63:0] w;\n  assign w = {w1, w0};\n")
        f.write("  always_comb begin\n    d = '0;\n    case (w[6:0])\n")
        f.write("\n".join(lines))
        f.write("\n      default: ;\n    endcase\n  end\nendmodule\n")
    print("generated %d entries" % len(entries))


if __name__ == "__main__":
    main()
